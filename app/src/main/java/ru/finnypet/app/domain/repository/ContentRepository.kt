package ru.finnypet.app.domain.repository

import ru.finnypet.app.domain.content.ContentPack

/**
 * Учебный контент: товары, цели, задания, словарь, тексты и числа экономики.
 *
 * Метод не приостанавливаемый намеренно. Контент лежит в ассетах внутри APK,
 * читается один раз за запуск и не меняется по ходу игры — это не поход в
 * сеть и не запрос к базе. Приостановка здесь заставила бы каждый вызов
 * тащить за собой корутинный контекст ради чтения нескольких килобайт.
 */
interface ContentRepository {

    fun pack(): ContentPack
}
