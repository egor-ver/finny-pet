package ru.finnypet.app.ui.theme

import androidx.compose.runtime.staticCompositionLocalOf

/**
 * Настройка движения, доступная любому компоненту без проброса через все
 * экраны. Звук раздаётся рядом, через `LocalGameAudio`.
 *
 * ТЗ требует, чтобы звук и анимации можно было отключить, а критически
 * важная информация не передавалась только звуком или движением. Флаг
 * читается из настроек в MainActivity и раздаётся отсюда: компоненту не
 * нужно знать ни про репозиторий, ни про корутины.
 *
 * По умолчанию включено — отключение это осознанный выбор пользователя,
 * а не состояние по умолчанию.
 */
val LocalAnimationsEnabled = staticCompositionLocalOf { true }
