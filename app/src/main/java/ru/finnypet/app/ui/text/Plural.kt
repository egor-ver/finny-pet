package ru.finnypet.app.ui.text

import kotlin.math.abs

/** Форма слова при числе: одна монета, две монеты, пять монет. */
enum class WordForm { ONE, FEW, MANY }

/**
 * Русское правило выбора формы.
 *
 * Считаем сами, а не через `plurals` из ресурсов: форму Android выбирает по
 * локали устройства, а не по языку строк. На телефоне с английским языком
 * русские варианты подставляются по английскому правилу, и «80 монет»
 * превращается в «80 монеты». Игра русскоязычная по ТЗ, поэтому и правило
 * должно быть русским независимо от настроек устройства.
 */
fun wordFormOf(amount: Int): WordForm {
    val value = abs(amount)
    // Одиннадцать, двенадцать и далее до девятнадцати — исключение:
    // последняя цифра обманывает, «21 монета», но «11 монет».
    if (value % 100 in 11..19) return WordForm.MANY
    return when (value % 10) {
        1 -> WordForm.ONE
        2, 3, 4 -> WordForm.FEW
        else -> WordForm.MANY
    }
}
